// Writes the reference documentation from the contract tags: a README with the tag table and the package index, and
// one page per package that exports something. The output depends only on the tags and the declarations, never on
// the machine: names sorted in code-unit order, `\n` line endings, paths relative to the repository.
import {
  describeValue,
  kindName,
  kindNamePlural,
  TAG_DEFINITIONS,
  type PublicExport,
  type TagDefinition,
} from './contract-tags.ts';

/** The folder of the reference, from the repository root. */
export const REFERENCE_DIR = 'docs/reference';

export interface ReferencedSubpath {
  /** The import specifier: `@yaltaan/core/result`. */
  readonly specifier: string;
  readonly exports: readonly PublicExport[];
}

export interface ReferencedPackage {
  /** The folder name, which names the package page: `core` → `core.md`. */
  readonly folder: string;
  readonly name: string;
  readonly subpaths: readonly ReferencedSubpath[];
}

const GENERATED =
  'Generated by `node scripts/check-contract-tags.ts --update` from the contract tags of the published declarations ' +
  '([ADR 0012](../adr/0012-contract-tag-checker.md)); never edited by hand: the verification gate fails when this ' +
  'folder differs from what the tags give.';

/** Renders every file of the reference, keyed by its name inside `REFERENCE_DIR`. */
export function renderReference(packages: readonly ReferencedPackage[]): ReadonlyMap<string, string> {
  const files = new Map<string, string>();
  const index: string[] = [];
  for (const referenced of packages) {
    const count = referenced.subpaths.reduce((sum, subpath) => sum + subpath.exports.length, 0);
    if (count === 0) {
      index.push(`- \`${referenced.name}\`: no public export yet.`);
      continue;
    }
    index.push(`- [\`${referenced.name}\`](${referenced.folder}.md): ${count} public export(s).`);
    files.set(`${referenced.folder}.md`, renderPackage(referenced));
  }
  files.set(
    'README.md',
    lines(['# Reference', '', GENERATED, '', ...renderTagTable(), '', '## Packages', '', ...index]),
  );
  return files;
}

function renderTagTable(): string[] {
  const out = [
    '## Contract tags',
    '',
    'An export that runs (a function, a constant that can be called, a class) carries the whole contract; an export ' +
      'that never runs (a constant, an interface, a type alias) carries `@since` and its stability only. Any tag ' +
      'missing from this table fails the gate.',
    '',
    '| Tag | Value | Carried by | Presence | Meaning |',
    '|---|---|---|---|---|',
  ];
  for (const definition of TAG_DEFINITIONS) {
    out.push(
      `| \`@${definition.name}\` | ${describeValue(definition)} | ${describeKinds(definition)} | ` +
        `${describePresence(definition)} | ${definition.meaning} |`,
    );
  }
  return out;
}

function describeKinds(definition: TagDefinition): string {
  return definition.appliesTo.map((kind) => kindNamePlural(kind)).join(', ');
}

function describePresence(definition: TagDefinition): string {
  const presence = definition.presence;
  if (typeof presence === 'object') {
    const members = TAG_DEFINITIONS.filter(
      (other) => typeof other.presence === 'object' && other.presence.group === presence.group,
    );
    return `either ${members.map((member) => `\`@${member.name}\``).join(' or ')}, never both`;
  }
  if (presence === 'required') {
    return definition.repeat ? 'required, repeatable' : 'required, once';
  }
  return definition.repeat ? 'optional, repeatable' : 'optional, once';
}

function renderPackage(referenced: ReferencedPackage): string {
  const out = [`# \`${referenced.name}\``, '', GENERATED];
  for (const subpath of referenced.subpaths) {
    out.push('', `## \`${subpath.specifier}\``);
    for (const entry of subpath.exports) {
      out.push('', ...renderExport(entry));
    }
  }
  return lines(out);
}

function renderExport(entry: PublicExport): string[] {
  const out = [`### \`${entry.name}\``, '', `A ${kindName(entry.kind)}.`];
  if (entry.documentation !== '') {
    out.push('', ...paragraphs(entry.documentation));
  }
  if (entry.declarations.length > 0) {
    out.push('', '```ts', ...entry.declarations.join('\n').split('\n'), '```');
  }
  const contract = TAG_DEFINITIONS.filter((definition) => definition.role === 'contract');
  const rows = contract.flatMap((definition) =>
    entry.tags
      .filter((tag) => tag.name === definition.name)
      .map((tag) => `| \`@${tag.name}\` | ${cell(tag.text === '' ? 'yes' : tag.text)} |`),
  );
  if (rows.length > 0) {
    out.push('', '| Contract | Value |', '|---|---|', ...rows);
  }
  for (const tag of entry.tags) {
    const definition = TAG_DEFINITIONS.find((candidate) => candidate.name === tag.name);
    if (definition?.role !== 'documentary') {
      continue;
    }
    if (tag.name === 'example') {
      const code = tag.text.split('\n');
      out.push('', '**Example**', '', ...(tag.text.includes('```') ? code : ['```ts', ...code, '```']));
    } else {
      out.push(
        '',
        `**@${tag.name}** ${paragraphs(tag.text)
          .filter((line) => line !== '')
          .join(' ')}`,
      );
    }
  }
  return out;
}

// Markdown here keeps one line per paragraph: lines of a JSDoc paragraph are joined, blank lines separate paragraphs,
// and fenced code is kept as written.
function paragraphs(text: string): string[] {
  const out: string[] = [];
  let paragraph: string[] = [];
  let fenced = false;
  const flush = (): void => {
    if (paragraph.length > 0) {
      out.push(paragraph.join(' '));
      paragraph = [];
    }
  };
  for (const raw of text.split('\n')) {
    const line = fenced ? raw : raw.trim();
    if (line.trimStart().startsWith('```')) {
      flush();
      fenced = !fenced;
      out.push(line.trimStart());
    } else if (fenced) {
      out.push(line);
    } else if (line === '') {
      flush();
      if (out.length > 0 && out[out.length - 1] !== '') {
        out.push('');
      }
    } else {
      paragraph.push(line);
    }
  }
  flush();
  while (out[out.length - 1] === '') {
    out.pop();
  }
  return out;
}

function cell(text: string): string {
  return text.replace(/\s+/g, ' ').replaceAll('|', '\\|');
}

function lines(out: readonly string[]): string {
  return `${out.join('\n')}\n`;
}
